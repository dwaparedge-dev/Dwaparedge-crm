import { z } from "zod";
import { optionalText, pageParams, uuid } from "@/lib/validation";

/** Control characters become spaces (a NUL byte would make Postgres refuse the row); runs of spaces collapse; ends are trimmed. */
const clean = (s: string) => s.replace(/[\u0000-\u001f\u007f]/g, " ").replace(/\s+/g, " ").trim();

const plain = (label: string, max: number) =>
  z
    .string({ error: `${label} is required` })
    .transform(clean)
    .pipe(z.string().min(1, `${label} is required`).max(max, `${label} can be at most ${max} characters`));

/** Free text that may be left out: blank becomes undefined. */
const optionalPlain = (max: number) =>
  z
    .string()
    .transform(clean)
    .pipe(z.string().max(max))
    .transform((s) => s || undefined)
    .optional();

/** Short machine labels such as "landing" or "navbar". */
const label = z.string().trim().toLowerCase().regex(/^[a-z0-9_-]{1,50}$/, "Use letters, digits, - or _ (up to 50)");

/** 10 digits; a +91 / 91 / 0 prefix and any spaces or dashes are dropped. */
export function normaliseMobile(v: string): string {
  const d = v.replace(/\D/g, "");
  if (d.length === 12 && d.startsWith("91")) return d.slice(2);
  if (d.length === 11 && d.startsWith("0")) return d.slice(1);
  return d;
}

export const demoRequestInputSchema = z.object({
  name: plain("Name", 120),
  company: plain("Company", 200),
  mobile: z
    .string({ error: "Mobile is required" })
    .transform(normaliseMobile)
    .pipe(z.string().regex(/^[6-9]\d{9}$/, "Enter a valid 10-digit mobile number")),
  email: z.string({ error: "Email is required" }).trim().toLowerCase().email("Enter a valid email").max(254),
  source: label.default("landing"),
  entryPoint: label.optional(),
  /** Generated by the form once per page load, so a retried submit is recognised instead of creating a second request. */
  externalRef: z.string().trim().regex(/^[A-Za-z0-9_-]{8,100}$/, "Invalid reference").optional(),
  /** The visitor's address and browser, as seen by the FactoOne server (the CRM only sees that server). */
  submitterIp: optionalPlain(64),
  userAgent: optionalPlain(300),
});
export type DemoRequestInput = z.infer<typeof demoRequestInputSchema>;

// ---- Staff side: the Demo requests page ----

export const DEMO_REQUEST_STATUSES = ["new", "contacted", "scheduled", "done", "spam"] as const;
export type DemoRequestStatus = (typeof DEMO_REQUEST_STATUSES)[number];

/** Without `status`, the list shows every request except spam; spam has its own tab. */
export const listDemoRequestsSchema = pageParams.extend({
  status: z.enum(DEMO_REQUEST_STATUSES).optional(),
  ownerId: uuid.optional(),
  sort: z.enum(["created", "name", "company"]).default("created"),
  dir: z.enum(["asc", "desc"]).default("desc"),
});
export type ListDemoRequestsParams = z.infer<typeof listDemoRequestsSchema>;

/** Only the fields that are sent change; an empty owner or notes value clears it. */
export const updateDemoRequestSchema = z
  .object({
    ownerId: z.preprocess((v) => (v === "" ? null : v), uuid.nullable()).optional(),
    // Notes keep their line breaks; only NUL bytes (which Postgres refuses in text) are removed.
    notes: z.preprocess((v) => (typeof v === "string" ? v.replace(/\u0000/g, "") : v), optionalText(5000)).optional(),
  })
  .refine((v) => v.ownerId !== undefined || v.notes !== undefined, { message: "Nothing to update" });
export type UpdateDemoRequestInput = z.infer<typeof updateDemoRequestSchema>;

export const demoRequestStatusSchema = z.object({ status: z.enum(DEMO_REQUEST_STATUSES) });
export type DemoRequestStatusInput = z.infer<typeof demoRequestStatusSchema>;
